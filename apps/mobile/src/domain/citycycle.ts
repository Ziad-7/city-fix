/** The order a pickup moves through (cancelled is a side exit from `requested`). */
export const PICKUP_STATUS_ORDER: readonly PickupStatus[] = ['requested', 'accepted', 'weighed', 'completed'];

/** Pickup timelines reuse `TimelineEntry` (status is an incident status): this is the mapping. */
export const PICKUP_TIMELINE_STATUS: Record<PickupStatus, IncidentStatus> = {
  requested: 'received',
  accepted: 'assigned',
  weighed: 'in_progress',
  completed: 'resolved',
  cancelled: 'closed',
};

/**
 * Which `StatusChip` colour to use for a pickup status (chips take an incident status):
 * requested grey, accepted blue, weighed amber, completed green, cancelled grey.
 */
export const pickupChipStatus = (s: PickupStatus): IncidentStatus => PICKUP_TIMELINE_STATUS[s];

