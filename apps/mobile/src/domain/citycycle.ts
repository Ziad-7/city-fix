// ---- Earnings periods ----

export type EarningsPeriodKind = 'today' | 'week';

/** `from`/`to` (ISO) of "today" (since local midnight) or "this week" (the last 7 days, today included). */
export function earningsRange(kind: EarningsPeriodKind, now: Date = new Date()): EarningsQuery {
  const start = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  if (kind === 'week') start.setDate(start.getDate() - 6);
  return { from: start.toISOString(), to: now.toISOString() };
}

/** What the collector is expected to pay the household: the weighed value for a paid pickup, nothing for a free one. */
export const suggestedPaymentEgp = (p: Pick<RecyclingPickup, 'mode' | 'totalValueEgp'>): number => (p.mode === 'paid' ? (p.totalValueEgp ?? 0) : 0);

/** The collector's current job is the one they accepted and have not finished. */
export const isCurrentJob = (p: Pick<RecyclingPickup, 'status'>): boolean => p.status === 'accepted' || p.status === 'weighed';
